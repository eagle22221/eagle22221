#!/usr/bin/env python3
"""Turn the web interface (binspect/web) into a C source file.

    embed_web.py WEB_DIR OUTPUT.c

The native binspect serves its interface from memory, so the one program
file is all there is to copy. The files in WEB_DIR are the same ones the
Python server reads from disk: they are embedded unchanged, each with the
path it has under /static/ and the Content-Type the Python server gives it.
Files of any other type are left out, just as the Python server refuses to
serve them.

Only the standard library is used, and the output depends on nothing but the
contents of WEB_DIR, so repeated builds produce identical files.
"""
import os
import sys

# The same table as CONTENT_TYPES in binspect/server.py (the test-suite checks
# that the two agree).
CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8", ".woff2": "font/woff2",
    ".svg": "image/svg+xml", ".txt": "text/plain; charset=utf-8", ".png": "image/png",
}


def collect(web_dir):
    """(url path, content type, bytes) for every servable file, sorted by path."""
    found = []
    for folder, dirs, files in os.walk(web_dir):
        dirs.sort()
        for name in sorted(files):
            full = os.path.join(folder, name)
            ctype = CONTENT_TYPES.get(os.path.splitext(name)[1].lower())
            if ctype is None or not os.path.isfile(full):
                continue
            relative = os.path.relpath(full, web_dir).replace(os.sep, "/")
            with open(full, "rb") as f:
                found.append((relative, ctype, f.read()))
    found.sort(key=lambda item: item[0])
    return found


def c_string(text):
    out = []
    for ch in text.encode("utf-8"):
        if ch in (0x22, 0x5C):                  # " and \
            out.append("\\" + chr(ch))
        elif 0x20 <= ch < 0x7F:
            out.append(chr(ch))
        else:
            out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def render(assets):
    lines = [
        "/* Generated by tools/embed_web.py from binspect/web. Do not edit:",
        " * change the files there and build again. */",
        '#include "server.h"',
        "",
    ]
    for index, (path, _ctype, data) in enumerate(assets):
        lines.append("/* %s */" % path.replace("*/", "* /"))
        lines.append("static const unsigned char asset_%d[] = {" % index)
        for start in range(0, len(data), 20):
            lines.append("    " + ",".join(str(b) for b in data[start:start + 20]) + ",")
        if not data:
            lines.append("    0")                # C has no empty arrays
        lines.append("};")
        lines.append("")
    lines.append("const WebAsset WEB_ASSETS[] = {")
    for index, (path, ctype, data) in enumerate(assets):
        lines.append("    {%s, %s, asset_%d, %d}," % (c_string(path), c_string(ctype), index, len(data)))
    lines.append("    {NULL, NULL, NULL, 0}")
    lines.append("};")
    lines.append("")
    lines.append("const size_t WEB_ASSET_COUNT = %d;" % len(assets))
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: embed_web.py WEB_DIR OUTPUT.c\n")
        return 2
    web_dir, output = argv[1], argv[2]
    assets = collect(web_dir)
    if not any(path == "index.html" for path, _ctype, _data in assets):
        sys.stderr.write("embed_web.py: %s has no index.html\n" % web_dir)
        return 1
    text = render(assets)
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    # Write next to the target and rename, so a failed run never leaves a
    # half-written source file for make to compile.
    temporary = output + ".tmp"
    with open(temporary, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    os.replace(temporary, output)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
