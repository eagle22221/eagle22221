#!/usr/bin/env python3
"""Write src/unicode_data.h: the character tables behind pystr.c.

    gen_unicode.py OUTPUT.h

The decode workbench reports errors with Python's repr() of what the user
typed, reads numbers with int() and takes the letters of a Vigenere key or a
substitution map with str.isalpha() and str.upper(). To give the same answers
the C edition needs the same character properties, so they are copied here
from the Python that is the reference (its `unicodedata.unidata_version` is
recorded in the output). Characters below U+0080 are handled in code.

The output depends only on the Unicode version of the Python that runs this.
"""
import sys
import unicodedata

FIRST, LIMIT = 0x80, 0x110000


def ranges(predicate):
    out, start = [], None
    for cp in range(FIRST, LIMIT):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, LIMIT - 1))
    return out


def decimal_runs():
    """Runs of decimal digits; every run starts at a digit zero and counts up."""
    runs = ranges(lambda cp: unicodedata.decimal(chr(cp), None) is not None)
    for lo, hi in runs:
        for cp in range(lo, hi + 1):
            assert unicodedata.decimal(chr(cp)) == (cp - lo) % 10, hex(cp)
    return runs


def upper_tables():
    """str.upper() of every letter that changes: runs with one offset, and
    the letters whose upper-case form is more than one character."""
    deltas, special = [], []
    for cp in range(FIRST, LIMIT):
        ch = chr(cp)
        if not ch.isalpha():
            continue
        up = ch.upper()
        if len(up) != 1:
            assert 2 <= len(up) <= 3, hex(cp)
            special.append((cp, [ord(c) for c in up]))
        elif up != ch:
            delta = ord(up) - cp
            if deltas and deltas[-1][1] == cp - 1 and deltas[-1][2] == delta:
                deltas[-1][1] = cp
            else:
                deltas.append([cp, cp, delta])
    return deltas, special


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    not_printable = ranges(lambda cp: not chr(cp).isprintable())
    alpha = ranges(lambda cp: chr(cp).isalpha())
    spaces = [cp for cp in range(LIMIT) if chr(cp).isspace()]
    decimals = decimal_runs()
    deltas, special = upper_tables()
    assert all(not chr(cp).isalpha() or chr(cp).upper().isascii() for cp in range(FIRST))

    lines = [
        "/* Generated by tools/gen_unicode.py from Python's unicodedata (Unicode %s)."
        % unicodedata.unidata_version,
        " * Do not edit. Characters below U+0080 are not listed. */",
        "#ifndef VEX_UNICODE_DATA_H",
        "#define VEX_UNICODE_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct { uint32_t lo, hi; } UniRange;",
        "typedef struct { uint32_t lo, hi; int32_t delta; } UniDelta;",
        "typedef struct { uint32_t cp; uint8_t n; uint32_t to[3]; } UniSpecial;",
        "",
    ]

    def emit_ranges(name, comment, rows):
        lines.append("/* %s */" % comment)
        lines.append("static const UniRange %s[] = {" % name)
        for i in range(0, len(rows), 4):
            lines.append("    " + " ".join("{0x%x, 0x%x}," % row for row in rows[i:i + 4]))
        lines.append("};")
        lines.append("")

    emit_ranges("UNI_NOT_PRINTABLE", "not str.isprintable()", not_printable)
    emit_ranges("UNI_ALPHA", "str.isalpha()", alpha)
    emit_ranges("UNI_DECIMAL", "decimal digits: the value is (cp - lo) % 10", decimals)
    lines.append("/* str.isspace(), all of them */")
    lines.append("static const uint32_t UNI_SPACE[] = {")
    lines.append("    " + " ".join("0x%x," % cp for cp in spaces))
    lines.append("};")
    lines.append("")
    lines.append("/* str.upper() of a letter: cp + delta */")
    lines.append("static const UniDelta UNI_UPPER[] = {")
    for i in range(0, len(deltas), 3):
        lines.append("    " + " ".join("{0x%x, 0x%x, %d}," % tuple(row) for row in deltas[i:i + 3]))
    lines.append("};")
    lines.append("")
    lines.append("/* letters whose str.upper() is two or three characters */")
    lines.append("static const UniSpecial UNI_UPPER_SPECIAL[] = {")
    for cp, to in special:
        padded = to + [0] * (3 - len(to))
        lines.append("    {0x%x, %d, {0x%x, 0x%x, 0x%x}}," % (cp, len(to), *padded))
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    with open(argv[1], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv)
