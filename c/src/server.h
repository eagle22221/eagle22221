/* The graphical interface: `binspect gui [PATH] [--port N] [--no-browser]`
 * (port of server.py).
 *
 * A small HTTP server bound to 127.0.0.1 that serves the single-page
 * interface of binspect/web (compiled into the program, see
 * tools/embed_web.py) and a JSON API over the same views the command line
 * prints. */
#ifndef BINSPECT_SERVER_H
#define BINSPECT_SERVER_H

#include "cli.h"

/* One file of the web interface. `path` is its place under /static/. */
typedef struct {
    const char *path;
    const char *content_type;
    const unsigned char *data;
    size_t size;
} WebAsset;

/* Generated by tools/embed_web.py; sorted by path, ends with a NULL path. */
extern const WebAsset WEB_ASSETS[];
extern const size_t WEB_ASSET_COUNT;

/* The `gui` command: serves until interrupted (Ctrl+C). */
void cmd_gui(Session *s);

/* True when the program was started on Windows by a double-click or by
 * dropping something on it (it owns its console window), which is when a
 * bare start should open the graphical interface. Always false elsewhere. */
bool gui_started_from_desktop(void);
/* Is `path` an existing file or folder? */
bool gui_can_open(const char *path);

#endif
